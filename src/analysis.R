# Generic helper function to run any classifier model (LDA/QDA) on any dataset
evaluate_classifier <- function(train_path, test_path = "oes_test_holdout.csv", method_func, method_name, dataset_label) {
  cat(sprintf("=== %s MODEL ON: %s ===\n", toupper(method_name), toupper(dataset_label)))

  # Read datasets
  train <- read.csv(train_path)
  test  <- read.csv(test_path)
  train$grade <- factor(train$grade)
  test$grade  <- factor(test$grade)

  # 1. Train the model
  fit <- method_func(grade ~ C + Si + Mn + Cr + Mo + Ni, data = train)
  if (method_name == "LDA") {
    print(fit) # Only print coefficients detail for LDA
  }

  # 2. Evaluate LOOCV (Leave-One-Out Cross-Validation)
  cv <- method_func(grade ~ C + Si + Mn + Cr + Mo + Ni, data = train, CV = TRUE)
  conf_cv <- table(Truth = train$grade, Predicted = cv$class)
  cat(sprintf("\n%s LOOCV Confusion Matrix:\n", method_name))
  print(conf_cv)
  cat(sprintf("%s LOOCV Accuracy: %.2f%%\n\n", method_name, sum(diag(conf_cv)) / sum(conf_cv) * 100))

  # 3. Evaluate on the independent holdout test set
  pred_test <- predict(fit, newdata = test)
  conf_test <- table(Truth = test$grade, Predicted = pred_test$class)
  cat(sprintf("%s Test Confusion Matrix:\n", method_name))
  print(conf_test)
  cat(sprintf("%s Test Accuracy: %.2f%%\n\n", method_name, sum(diag(conf_test)) / sum(conf_test) * 100))

  return(fit)
}

