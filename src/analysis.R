fmt_cell <- function(x) {
  x <- x[is.finite(x)]
  res <- shapiro.test(x)
  w_str <- sprintf("%.4f", unname(res$statistic))
  p_str <- if (res$p.value < 0.001) {
    sprintf("%.2e", res$p.value)
  } else {
    sprintf("%.3f", res$p.value)
  }
  paste0(w_str, " (", p_str, ")")
}

