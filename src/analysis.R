clean_single_oes <- function(filepath, grade_label) {
  lines <- readLines(filepath, warn = FALSE)
  header_idx <- grep("^,Fe", lines)[1]
  if (is.na(header_idx)) return(NULL) # ignore if error

  col_names <- trimws(unlist(strsplit(lines[header_idx], ",")))
  col_names[1] <- "shot"

  raw_df <- read.csv(text = lines[(header_idx + 3):length(lines)], header = FALSE)
  colnames(raw_df) <- col_names[1:ncol(raw_df)]

  clean_df <- raw_df[grepl("^[0-9]+$", trimws(raw_df$shot)), ]
  clean_df$shot <- as.integer(trimws(clean_df$shot))

  elements <- c("C", "Si", "Mn", "Cr", "Mo", "Ni")
  for (el in elements) {
    val_str <- trimws(as.character(clean_df[[el]]))
    is_lod  <- grepl("\\[<\\]", val_str)
    num_val <- as.numeric(gsub("\\[<\\]", "", val_str))
    num_val[is_lod] <- num_val[is_lod] / 2
    clean_df[[el]] <- num_val
  }

  clean_df$grade <- paste0("SS", grade_label)
  clean_df$block <- tools::file_path_sans_ext(basename(filepath))

  return(clean_df[, c("grade", "block", "shot", elements)])
}

