"""4. **Multivariate Normality Test**
   - Performs Mardia's test of multivariate skewness and kurtosis for each steel grade to verify if the chemical elements follow a multivariate normal distribution.
"""

mardia <- function(x) {
  x <- as.matrix(x); n <- nrow(x); p <- ncol(x)
  xc <- scale(x, center = TRUE, scale = FALSE)
  S <- crossprod(xc) / n # ML covariance
  D <- xc %*% solve(S) %*% t(xc)
  b1 <- mean(D^3) # multivariate skewness
  b2 <- mean(diag(D)^2) # multivariate kurtosis
  skew_stat <- n * b1 / 6
  skew_df <- p * (p + 1) * (p + 2) / 6
  kurt_z <- (b2 - p * (p + 2)) / sqrt(8 * p * (p + 2) / n)
  c(n = n, skew_stat = skew_stat,
    skew_p = pchisq(skew_stat, skew_df, lower.tail = FALSE),
    kurt_z = kurt_z, kurt_p = 2 * pnorm(-abs(kurt_z)))
}

