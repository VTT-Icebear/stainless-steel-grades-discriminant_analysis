"""11. **Element Contribution to Group Separation**
    - Multiplies each LDA coefficient by the gap between two group means, so the result does not depend on measurement units.
    - Shows how much each element adds to the LD1 gap (304 vs 316 family) and the LD2 gaps (standard vs L grade).
"""

# Contribution of each element = LDA coefficient x gap between group means.
# LDA coefficients already account for within-grade variation, so this shows
# how much of the separation each element supplies, whatever its scale.
m <- lda_model$means      # group means (rows: grades, columns: elements)
b <- lda_model$scaling    # LDA coefficients (rows: elements, columns: LD1-LD3)

contrib <- function(axis, from, to, label) {
  gap <- colMeans(m[to, , drop = FALSE]) - colMeans(m[from, , drop = FALSE])
  gap <- gap[rownames(b)]                       # same element order as b
  x   <- b[, axis] * gap
  cat("\n", label, " (", axis, " gap = ", round(sum(x), 2), ")\n", sep = "")
  print(data.frame(Element      = names(x),
                   Contribution = round(x, 2),
                   Share_pct    = round(100 * x / sum(x), 1)),
        row.names = FALSE)
}

